"""Exploratory data analysis for the customer segmentation project.

All data is SYNTHETIC (generated by src/data_generator.py).

The script:
    1. loads data/customers.csv and data/orders.csv,
    2. prints shape, dtypes, missing values, duplicates and integrity checks,
    3. prints descriptive statistics and several aggregations,
    4. saves a few charts to figures/.

Run from the project root (after python src/data_generator.py):
    python src/eda.py
"""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # non-interactive backend: figures are only saved to files

import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402
import seaborn as sns  # noqa: E402

PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"
FIGURES_DIR = PROJECT_DIR / "figures"
REQUIRED_FILES = ("customers.csv", "orders.csv")

pd.set_option("display.width", 120)
pd.set_option("display.max_columns", 20)
sns.set_theme(style="whitegrid")


def load_data() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load the customers and orders tables with date columns parsed.

    Raises:
        FileNotFoundError: If one of the required CSV files is missing. The message
            tells the user which files are missing and how to create them.
    """
    # Fail early with a clear hint instead of a raw pandas traceback
    missing = [name for name in REQUIRED_FILES if not (DATA_DIR / name).is_file()]
    if missing:
        raise FileNotFoundError(
            f"Missing data files in {DATA_DIR}: {', '.join(missing)}. "
            "Run 'python src/data_generator.py' from the project root first."
        )

    customers = pd.read_csv(DATA_DIR / "customers.csv", parse_dates=["signup_date"])
    orders = pd.read_csv(DATA_DIR / "orders.csv", parse_dates=["order_date"])
    return customers, orders


def print_section(title: str) -> None:
    """Print a section header."""
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def overview(name: str, df: pd.DataFrame) -> None:
    """Print shape, dtypes, missing values and duplicate count for one table."""
    print_section(f"Overview: {name}")
    print(f"Shape: {df.shape[0]} rows x {df.shape[1]} columns")
    print("\nDtypes:")
    print(df.dtypes.to_string())
    print("\nMissing values per column:")
    print(df.isna().sum().to_string())
    print(f"\nDuplicated rows: {df.duplicated().sum()}")


def integrity_checks(customers: pd.DataFrame, orders: pd.DataFrame) -> None:
    """Check keys and date logic between the two tables."""
    print_section("Integrity checks")
    print(f"Duplicated customer_id in customers: {customers['customer_id'].duplicated().sum()}")
    print(f"Duplicated order_id in orders: {orders['order_id'].duplicated().sum()}")

    unknown = ~orders["customer_id"].isin(customers["customer_id"])
    print(f"Orders with unknown customer_id: {unknown.sum()}")

    no_orders = ~customers["customer_id"].isin(orders["customer_id"])
    print(f"Customers without any order: {no_orders.sum()}")

    merged = orders.merge(customers[["customer_id", "signup_date"]], on="customer_id", how="left")
    print(f"Orders dated before signup: {(merged['order_date'] < merged['signup_date']).sum()}")
    print(f"Order date range: {orders['order_date'].min().date()} to {orders['order_date'].max().date()}")


def descriptive_stats(customers: pd.DataFrame, orders: pd.DataFrame) -> None:
    """Print descriptive statistics for numeric columns."""
    print_section("Descriptive statistics")
    print("Customers (numeric):")
    print(customers[["age", "newsletter_subscriber"]].describe().round(2).to_string())
    print("\nOrders (numeric):")
    cols = ["order_value", "items_count", "discount_used"]
    print(orders[cols].describe().round(2).to_string())
    skew = orders["order_value"].skew()
    print(f"\nSkewness of order_value: {skew:.2f} (positive = long right tail)")


def build_customer_table(customers: pd.DataFrame, orders: pd.DataFrame) -> pd.DataFrame:
    """Aggregate orders to one row per customer and join the profile columns."""
    per_customer = (
        orders.groupby("customer_id")
        .agg(
            n_orders=("order_id", "count"),
            total_spend=("order_value", "sum"),
            last_order=("order_date", "max"),
        )
        .reset_index()
    )
    out = customers.merge(per_customer, on="customer_id", how="left")
    out["n_orders"] = out["n_orders"].fillna(0).astype(int)
    out["total_spend"] = out["total_spend"].fillna(0.0)
    return out


def aggregations(customers: pd.DataFrame, orders: pd.DataFrame, cust: pd.DataFrame) -> pd.DataFrame:
    """Print the key aggregations and return the monthly table for plotting."""
    print_section("Aggregation 1: orders per customer (frequency)")
    print(cust["n_orders"].describe().round(2).to_string())
    print("\nShare of customers by number of orders (capped at 10+):")
    capped = cust["n_orders"].clip(upper=10)
    print(capped.value_counts(normalize=True).sort_index().round(3).to_string())

    print_section("Aggregation 2: customer spend concentration")
    spend = cust["total_spend"].sort_values(ascending=False)
    top_n = max(1, int(len(spend) * 0.2))
    top_share = spend.head(top_n).sum() / spend.sum()
    print(f"Top 20% of customers ({top_n}) account for {top_share:.1%} of total revenue")
    print("\nTotal spend per customer:")
    print(cust["total_spend"].describe().round(2).to_string())

    # Join the profile columns to orders for group comparisons
    enriched = orders.merge(
        customers[["customer_id", "country", "acquisition_channel"]], on="customer_id", how="left"
    )

    print_section("Aggregation 3: country comparison")
    by_country = (
        enriched.groupby("country")
        .agg(
            customers=("customer_id", "nunique"),
            orders=("order_id", "count"),
            revenue=("order_value", "sum"),
            avg_order_value=("order_value", "mean"),
        )
        .assign(orders_per_customer=lambda d: d["orders"] / d["customers"])
        .sort_values("revenue", ascending=False)
        .round(2)
    )
    print(by_country.to_string())

    print_section("Aggregation 4: acquisition channel comparison")
    by_channel = (
        enriched.groupby("acquisition_channel")
        .agg(
            customers=("customer_id", "nunique"),
            orders=("order_id", "count"),
            revenue=("order_value", "sum"),
            avg_order_value=("order_value", "mean"),
        )
        .assign(
            orders_per_customer=lambda d: d["orders"] / d["customers"],
            revenue_per_customer=lambda d: d["revenue"] / d["customers"],
        )
        .sort_values("revenue_per_customer", ascending=False)
        .round(2)
    )
    print(by_channel.to_string())

    print_section("Aggregation 5: discounts, payment methods and newsletter")
    by_discount = orders.groupby("discount_used")["order_value"].agg(["count", "mean", "median"]).round(2)
    print("Order value by discount usage:")
    print(by_discount.to_string())
    print("\nOrder share and mean value by payment method:")
    by_payment = orders.groupby("payment_method")["order_value"].agg(["count", "mean"]).round(2)
    by_payment["share"] = (by_payment["count"] / len(orders)).round(3)
    print(by_payment.to_string())
    print("\nCustomer averages by newsletter subscription:")
    by_news = cust.groupby("newsletter_subscriber")[["n_orders", "total_spend"]].mean().round(2)
    print(by_news.to_string())

    # Monthly activity over time
    monthly = (
        orders.assign(month=orders["order_date"].dt.to_period("M").dt.to_timestamp())
        .groupby("month")
        .agg(orders=("order_id", "count"), revenue=("order_value", "sum"))
        .reset_index()
    )
    print_section("Aggregation 6: monthly activity (first and last 3 months)")
    print(pd.concat([monthly.head(3), monthly.tail(3)]).round(2).to_string(index=False))
    return monthly


def save_charts(orders: pd.DataFrame, cust: pd.DataFrame, monthly: pd.DataFrame) -> None:
    """Save the EDA charts to figures/."""
    FIGURES_DIR.mkdir(exist_ok=True)

    # 1. Distribution of order value (log x-axis because of the long right tail)
    fig, ax = plt.subplots(figsize=(8, 5))
    sns.histplot(orders["order_value"], bins=50, log_scale=True, ax=ax, color="steelblue")
    ax.set_title("Distribution of order value (log scale)")
    ax.set_xlabel("Order value")
    ax.set_ylabel("Number of orders")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "order_value_distribution.png", dpi=120)
    plt.close(fig)

    # 2. Orders per customer
    fig, ax = plt.subplots(figsize=(8, 5))
    sns.histplot(cust["n_orders"], discrete=True, ax=ax, color="darkorange")
    ax.set_title("Orders per customer")
    ax.set_xlabel("Number of orders")
    ax.set_ylabel("Number of customers")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "orders_per_customer.png", dpi=120)
    plt.close(fig)

    # 3. Monthly orders and revenue
    fig, axes = plt.subplots(2, 1, figsize=(9, 7), sharex=True)
    sns.lineplot(data=monthly, x="month", y="orders", marker="o", ax=axes[0], color="seagreen")
    axes[0].set_title("Monthly number of orders")
    axes[0].set_xlabel("")
    axes[0].set_ylabel("Orders")
    sns.lineplot(data=monthly, x="month", y="revenue", marker="o", ax=axes[1], color="firebrick")
    axes[1].set_title("Monthly revenue")
    axes[1].set_xlabel("Month")
    axes[1].set_ylabel("Revenue")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "monthly_activity.png", dpi=120)
    plt.close(fig)

    # 4. Average revenue per customer by acquisition channel
    by_channel = (
        cust.groupby("acquisition_channel")["total_spend"].mean().sort_values(ascending=False).reset_index()
    )
    fig, ax = plt.subplots(figsize=(8, 5))
    sns.barplot(data=by_channel, x="acquisition_channel", y="total_spend", ax=ax, color="slateblue")
    ax.set_title("Average total spend per customer by acquisition channel")
    ax.set_xlabel("Acquisition channel")
    ax.set_ylabel("Average total spend")
    ax.tick_params(axis="x", rotation=20)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "spend_by_channel.png", dpi=120)
    plt.close(fig)

    print_section("Charts")
    print(f"Saved 4 charts to {FIGURES_DIR}")


def main() -> None:
    """Run the full EDA."""
    customers, orders = load_data()
    overview("customers", customers)
    overview("orders", orders)
    integrity_checks(customers, orders)
    descriptive_stats(customers, orders)
    cust = build_customer_table(customers, orders)
    monthly = aggregations(customers, orders, cust)
    save_charts(orders, cust, monthly)


if __name__ == "__main__":
    main()
