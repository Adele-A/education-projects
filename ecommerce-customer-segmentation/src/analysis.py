"""RFM scoring and k-means segmentation of customers.

All data is SYNTHETIC (generated by src/data_generator.py).

Steps:
    1. load data and compute RFM features per customer,
    2. build rule-based RFM scores and named segments,
    3. scale features, choose k with elbow and silhouette, fit k-means,
    4. profile segments and compare k-means with the rule-based segments,
    5. save charts to figures/ and metrics to reports/metrics.json.

The task is unsupervised, so there is no train/test split; all randomness
uses random_state=42.

Run from the project root (after python src/data_generator.py):
    python src/analysis.py
"""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # non-interactive backend: figures are only saved to files

import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402
import seaborn as sns  # noqa: E402
from sklearn.metrics import adjusted_rand_score  # noqa: E402

from eda import load_data  # noqa: E402
from utils import (  # noqa: E402
    RANDOM_STATE,
    add_rfm_scores,
    add_rule_based_segments,
    choose_k,
    clustering_quality,
    compute_rfm,
    evaluate_k_range,
    fit_kmeans,
    get_snapshot_date,
    prepare_features,
    profile_segments,
    relabel_by_monetary,
)

PROJECT_DIR = Path(__file__).resolve().parents[1]
FIGURES_DIR = PROJECT_DIR / "figures"
REPORTS_DIR = PROJECT_DIR / "reports"
K_VALUES = range(2, 9)

pd.set_option("display.width", 120)
pd.set_option("display.max_columns", 20)
sns.set_theme(style="whitegrid")


def print_section(title: str) -> None:
    """Print a section header."""
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def save_k_selection_chart(k_scores: pd.DataFrame, best_k: int) -> None:
    """Save the elbow (inertia) and silhouette curves side by side."""
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.5))
    sns.lineplot(data=k_scores, x="k", y="inertia", marker="o", ax=axes[0], color="steelblue")
    axes[0].set_title("Elbow plot: inertia by number of clusters")
    axes[0].set_xlabel("Number of clusters (k)")
    axes[0].set_ylabel("Inertia")

    sns.lineplot(data=k_scores, x="k", y="silhouette", marker="o", ax=axes[1], color="darkorange")
    axes[1].axvline(best_k, color="grey", linestyle="--", label=f"Chosen k = {best_k}")
    axes[1].set_title("Silhouette score by number of clusters")
    axes[1].set_xlabel("Number of clusters (k)")
    axes[1].set_ylabel("Silhouette score")
    axes[1].legend()
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "k_selection.png", dpi=120)
    plt.close(fig)


def save_segments_chart(rfm: pd.DataFrame, labels: pd.Series) -> None:
    """Save a scatter plot of frequency vs recency coloured by k-means cluster."""
    data = rfm.assign(cluster=labels.astype(str))
    order = sorted(data["cluster"].unique())
    fig, ax = plt.subplots(figsize=(8.5, 6))
    sns.scatterplot(
        data=data,
        x="recency",
        y="frequency",
        hue="cluster",
        hue_order=order,
        size="monetary",
        sizes=(15, 160),
        alpha=0.6,
        palette="tab10",
        ax=ax,
    )
    ax.set_yscale("log")
    ax.set_title("K-means segments: recency vs frequency (point size = total spend)")
    ax.set_xlabel("Recency (days since last order)")
    ax.set_ylabel("Frequency (number of orders, log scale)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "kmeans_segments.png", dpi=120)
    plt.close(fig)


def main() -> None:
    """Run the full segmentation analysis."""
    customers, orders = load_data()

    # 1. RFM features
    snapshot = get_snapshot_date(orders)
    rfm = compute_rfm(orders, snapshot)
    print_section("RFM features")
    print(f"Snapshot date: {snapshot.date()}")
    print(f"Customers with RFM values: {len(rfm)}")
    print(rfm.describe().round(2).to_string())

    # 2. Rule-based RFM segments
    scored = add_rule_based_segments(add_rfm_scores(rfm))
    rule_profile = profile_segments(rfm, scored["rfm_segment"])
    print_section("Rule-based RFM segments (quintile scores)")
    print(rule_profile.sort_values("avg_monetary", ascending=False).round(2).to_string())

    # 3. K-means: choose k, fit, evaluate
    x = prepare_features(rfm)
    k_scores = evaluate_k_range(x, K_VALUES, seed=RANDOM_STATE)
    best_k = choose_k(k_scores)
    print_section("Choosing the number of clusters")
    print(k_scores.round(4).to_string(index=False))
    print(f"\nChosen k (highest silhouette): {best_k}")

    labels = pd.Series(
        relabel_by_monetary(fit_kmeans(x, best_k, seed=RANDOM_STATE), rfm),
        index=rfm.index,
        name="cluster",
    )
    quality = clustering_quality(x, labels.to_numpy())
    print_section("K-means quality")
    print(f"Silhouette score (higher is better): {quality['silhouette']:.4f}")
    print(f"Davies-Bouldin index (lower is better): {quality['davies_bouldin']:.4f}")

    # 4. Segment profiles and comparison
    km_profile = profile_segments(rfm, labels)
    print_section("K-means segment profiles (cluster 0 = highest mean spend)")
    print(km_profile.round(3).to_string())

    ari = float(adjusted_rand_score(scored["rfm_segment"], labels))
    print_section("Comparison: k-means vs rule-based segments")
    print(f"Adjusted Rand Index (1 = identical grouping, ~0 = unrelated): {ari:.4f}")
    print("\nCustomers by rule-based segment (rows) and k-means cluster (columns):")
    print(pd.crosstab(scored["rfm_segment"], labels).to_string())

    # 5. Charts and metrics
    FIGURES_DIR.mkdir(exist_ok=True)
    REPORTS_DIR.mkdir(exist_ok=True)
    save_k_selection_chart(k_scores, best_k)
    save_segments_chart(rfm, labels)

    metrics = {
        "snapshot_date": str(snapshot.date()),
        "n_customers": int(len(rfm)),
        "random_state": RANDOM_STATE,
        "k_candidates": k_scores.round(6).to_dict(orient="records"),
        "chosen_k": best_k,
        "kmeans_quality": quality,
        "adjusted_rand_index_vs_rule_based": ari,
        "kmeans_segments": {
            str(cluster): {
                "customers": int(row["customers"]),
                "customer_share": float(row["customer_share"]),
                "revenue_share": float(row["revenue_share"]),
                "avg_recency_days": float(row["avg_recency"]),
                "avg_frequency": float(row["avg_frequency"]),
                "avg_monetary": float(row["avg_monetary"]),
            }
            for cluster, row in km_profile.iterrows()
        },
        "rule_based_segments": {
            str(name): {
                "customers": int(row["customers"]),
                "customer_share": float(row["customer_share"]),
                "revenue_share": float(row["revenue_share"]),
            }
            for name, row in rule_profile.iterrows()
        },
    }
    with open(REPORTS_DIR / "metrics.json", "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    print_section("Outputs")
    print(f"Saved charts to {FIGURES_DIR} (k_selection.png, kmeans_segments.png)")
    print(f"Saved metrics to {REPORTS_DIR / 'metrics.json'}")


if __name__ == "__main__":
    main()
