"""Run the SQL analysis from sql/queries.sql on the project's CSV tables.

All data is SYNTHETIC (generated by src/data_generator.py).

The script:
    1. loads data/customers.csv and data/orders.csv,
    2. copies them into an in-memory SQLite database (pandas.to_sql),
    3. splits sql/queries.sql into statements,
    4. runs each statement and prints its description and the first rows.

Run from the project root (after python src/data_generator.py):
    python src/run_sql.py
"""

import re
import sqlite3
from pathlib import Path

import pandas as pd

from eda import load_data

PROJECT_DIR = Path(__file__).resolve().parents[1]
QUERIES_FILE = PROJECT_DIR / "sql" / "queries.sql"
MAX_ROWS = 10  # number of result rows printed per query

pd.set_option("display.width", 120)
pd.set_option("display.max_columns", 20)

DESCRIPTION_PATTERN = re.compile(r"^--\s*(Q\d+:.*)$")


def build_database() -> sqlite3.Connection:
    """Load the CSV tables into an in-memory SQLite database.

    Dates are converted to YYYY-MM-DD text, which SQLite date functions understand.
    """
    customers, orders = load_data()
    customers = customers.assign(signup_date=customers["signup_date"].dt.strftime("%Y-%m-%d"))
    orders = orders.assign(order_date=orders["order_date"].dt.strftime("%Y-%m-%d"))

    conn = sqlite3.connect(":memory:")
    customers.to_sql("customers", conn, index=False, if_exists="replace")
    orders.to_sql("orders", conn, index=False, if_exists="replace")
    return conn


def split_queries(text: str) -> list[tuple[str, str]]:
    """Split the SQL file into (description, statement) pairs.

    A statement ends with a line that finishes with a semicolon. The description is
    the comment line starting with '-- Q<n>:'. Chunks without executable code
    (for example, the file header) are skipped.
    """
    queries = []
    current: list[str] = []
    for line in text.splitlines():
        current.append(line)
        if line.rstrip().endswith(";"):
            statement = "\n".join(current).strip()
            current = []

            code_lines = [l for l in statement.splitlines() if not l.strip().startswith("--")]
            if not "".join(code_lines).strip().rstrip(";").strip():
                continue  # only comments, nothing to run

            description = "(no description)"
            for l in statement.splitlines():
                match = DESCRIPTION_PATTERN.match(l.strip())
                if match:
                    description = match.group(1)
                    break
            queries.append((description, statement))
    return queries


def main() -> None:
    """Run every query in sql/queries.sql and print the first rows of each result."""
    if not QUERIES_FILE.is_file():
        raise FileNotFoundError(f"SQL file not found: {QUERIES_FILE}")

    queries = split_queries(QUERIES_FILE.read_text(encoding="utf-8"))
    conn = build_database()
    print(f"Loaded tables into in-memory SQLite. Running {len(queries)} queries.")

    try:
        for description, statement in queries:
            print(f"\n{'=' * 70}\n{description}\n{'=' * 70}")
            result = pd.read_sql_query(statement, conn)
            if result.empty:
                print("(no rows returned)")
                continue
            print(result.head(MAX_ROWS).to_string(index=False))
            if len(result) > MAX_ROWS:
                print(f"... showing first {MAX_ROWS} of {len(result)} rows")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
