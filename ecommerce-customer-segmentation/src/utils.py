"""Reusable helpers for the customer segmentation analysis.

All data is SYNTHETIC (generated by src/data_generator.py).

The functions here are free of printing and file I/O (except where noted),
so they can be unit-tested separately from src/analysis.py.
"""

import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.metrics import davies_bouldin_score, silhouette_score
from sklearn.preprocessing import StandardScaler

RFM_COLUMNS = ["recency", "frequency", "monetary"]
RANDOM_STATE = 42


def get_snapshot_date(orders: pd.DataFrame) -> pd.Timestamp:
    """Return the analysis date: one day after the last order in the data."""
    return orders["order_date"].max() + pd.Timedelta(days=1)


def compute_rfm(orders: pd.DataFrame, snapshot_date: pd.Timestamp) -> pd.DataFrame:
    """Compute Recency, Frequency and Monetary values per customer.

    Args:
        orders: Orders table with customer_id, order_id, order_date, order_value.
        snapshot_date: Reference date for recency.

    Returns:
        DataFrame indexed by customer_id with columns:
        - recency: days between the last order and the snapshot date,
        - frequency: number of orders,
        - monetary: total order value.
    """
    grouped = orders.groupby("customer_id")
    rfm = pd.DataFrame(
        {
            "recency": (snapshot_date - grouped["order_date"].max()).dt.days,
            "frequency": grouped["order_id"].count(),
            "monetary": grouped["order_value"].sum(),
        }
    )
    return rfm


def _quintile_score(values: pd.Series, ascending: bool = True) -> pd.Series:
    """Score values 1-5 by quintile.

    Ranking with method="first" breaks ties deterministically (by row order),
    so quintiles always exist even when many customers share the same value
    (for example, many customers with exactly one order).

    Args:
        values: Numeric series to score.
        ascending: If True, larger values get higher scores; if False, the
            scale is reversed (used for recency, where smaller is better).
    """
    ranks = values.rank(method="first", ascending=ascending)
    return pd.qcut(ranks, 5, labels=[1, 2, 3, 4, 5]).astype(int)


def add_rfm_scores(rfm: pd.DataFrame) -> pd.DataFrame:
    """Add quintile scores R, F, M (1-5, higher is better) and their sum."""
    out = rfm.copy()
    out["r_score"] = _quintile_score(out["recency"], ascending=False)
    out["f_score"] = _quintile_score(out["frequency"], ascending=True)
    out["m_score"] = _quintile_score(out["monetary"], ascending=True)
    out["rfm_total"] = out[["r_score", "f_score", "m_score"]].sum(axis=1)
    return out


def rule_based_segment(r_score: int, f_score: int) -> str:
    """Map R and F scores to a named business segment (rules checked in order)."""
    if r_score >= 4 and f_score >= 4:
        return "Champions"
    if r_score >= 3 and f_score >= 3:
        return "Loyal"
    if r_score <= 2 and f_score >= 3:
        return "At Risk"
    if r_score <= 2 and f_score <= 2:
        return "Lapsed"
    if r_score >= 4 and f_score <= 2:
        return "New / Promising"
    return "Occasional"


def add_rule_based_segments(scored: pd.DataFrame) -> pd.DataFrame:
    """Add a rule-based 'rfm_segment' column to a table with r_score and f_score."""
    out = scored.copy()
    out["rfm_segment"] = [
        rule_based_segment(r, f) for r, f in zip(out["r_score"], out["f_score"])
    ]
    return out


def prepare_features(rfm: pd.DataFrame) -> np.ndarray:
    """Build the scaled feature matrix for clustering.

    RFM values are right-skewed, so log(1 + x) is applied first, then each
    column is standardised to zero mean and unit variance.
    """
    logged = np.log1p(rfm[RFM_COLUMNS].to_numpy(dtype=float))
    return StandardScaler().fit_transform(logged)


def evaluate_k_range(x: np.ndarray, k_values: range, seed: int = RANDOM_STATE) -> pd.DataFrame:
    """Fit k-means for each k and collect inertia and silhouette score."""
    rows = []
    for k in k_values:
        model = KMeans(n_clusters=k, n_init=10, random_state=seed).fit(x)
        rows.append(
            {
                "k": k,
                "inertia": float(model.inertia_),
                "silhouette": float(silhouette_score(x, model.labels_)),
            }
        )
    return pd.DataFrame(rows)


def choose_k(k_scores: pd.DataFrame) -> int:
    """Pick the k with the highest silhouette score."""
    return int(k_scores.loc[k_scores["silhouette"].idxmax(), "k"])


def fit_kmeans(x: np.ndarray, k: int, seed: int = RANDOM_STATE) -> np.ndarray:
    """Fit k-means and return the cluster label of each row."""
    return KMeans(n_clusters=k, n_init=10, random_state=seed).fit_predict(x)


def relabel_by_monetary(labels: np.ndarray, rfm: pd.DataFrame) -> np.ndarray:
    """Renumber clusters so that cluster 0 has the highest mean monetary value.

    k-means labels are arbitrary; ordering them by value makes the output
    stable and easier to read.
    """
    means = pd.Series(rfm["monetary"].to_numpy()).groupby(labels).mean()
    order = means.sort_values(ascending=False).index
    mapping = {old: new for new, old in enumerate(order)}
    return np.array([mapping[label] for label in labels])


def clustering_quality(x: np.ndarray, labels: np.ndarray) -> dict[str, float]:
    """Return silhouette (higher is better) and Davies-Bouldin (lower is better)."""
    return {
        "silhouette": float(silhouette_score(x, labels)),
        "davies_bouldin": float(davies_bouldin_score(x, labels)),
    }


def profile_segments(rfm: pd.DataFrame, labels: pd.Series | np.ndarray) -> pd.DataFrame:
    """Summarise each segment: size, share and mean/median RFM values."""
    data = rfm[RFM_COLUMNS].copy()
    data["segment"] = np.asarray(labels)
    profile = data.groupby("segment").agg(
        customers=("recency", "size"),
        avg_recency=("recency", "mean"),
        avg_frequency=("frequency", "mean"),
        avg_monetary=("monetary", "mean"),
        median_monetary=("monetary", "median"),
        total_revenue=("monetary", "sum"),
    )
    profile["customer_share"] = profile["customers"] / profile["customers"].sum()
    profile["revenue_share"] = profile["total_revenue"] / profile["total_revenue"].sum()
    return profile
