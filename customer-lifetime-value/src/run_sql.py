"""Run the SQL queries from sql/queries.sql on the SYNTHETIC CLV data.

Loads data/customers.csv and data/transactions.csv into an in-memory SQLite
database (pandas.to_sql), splits the query file into statements, runs each one
and prints its description and the first rows of the result.

Run from the project root:
    python src/run_sql.py
"""

import re
import sqlite3
from pathlib import Path

import pandas as pd

from utils import load_data

PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"
SQL_FILE = PROJECT_DIR / "sql" / "queries.sql"

MAX_ROWS_PRINTED = 10


def build_database(data_dir: Path) -> sqlite3.Connection:
    """Create an in-memory SQLite database with the two CSV tables."""
    customers, transactions = load_data(data_dir)
    # Store dates as plain YYYY-MM-DD text so SQLite date functions work predictably
    customers["acquisition_date"] = customers["acquisition_date"].dt.strftime("%Y-%m-%d")
    transactions["transaction_date"] = transactions["transaction_date"].dt.strftime("%Y-%m-%d")

    conn = sqlite3.connect(":memory:")
    customers.to_sql("customers", conn, index=False)
    transactions.to_sql("transactions", conn, index=False)
    return conn


def split_queries(sql_text: str) -> list[tuple[str, str]]:
    """Split the file into (description, statement) pairs.

    Statements are separated by semicolons. The description is the comment line
    that starts with '-- Q<n>:'. Chunks without any SQL code are skipped.
    """
    queries = []
    for chunk in sql_text.split(";"):
        lines = chunk.strip().splitlines()
        description = next(
            (ln.strip()[2:].strip() for ln in lines if re.match(r"--\s*Q\d+:", ln.strip())),
            None,
        )
        code_lines = [ln for ln in lines if ln.strip() and not ln.strip().startswith("--")]
        if description is None or not code_lines:
            continue
        queries.append((description, "\n".join(lines)))
    return queries


def main() -> None:
    print("NOTE: all data is synthetic, generated by src/data_generator.py.")
    if not SQL_FILE.exists():
        raise FileNotFoundError(f"{SQL_FILE} not found.")

    conn = build_database(DATA_DIR)
    queries = split_queries(SQL_FILE.read_text(encoding="utf-8"))
    print(f"Loaded tables into in-memory SQLite. Running {len(queries)} queries.")

    for description, statement in queries:
        print(f"\n{description}")
        result = pd.read_sql_query(statement, conn)
        print(f"({len(result)} rows, showing up to {MAX_ROWS_PRINTED})")
        print(result.head(MAX_ROWS_PRINTED).to_string(index=False))

    conn.close()


if __name__ == "__main__":
    main()
