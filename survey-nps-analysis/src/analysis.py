"""Main analysis for the SYNTHETIC customer survey NPS dataset.

Steps:
  1. Overall NPS with a bootstrap confidence interval, and NPS by month.
  2. NPS by segment, plan, region, acquisition channel and tenure band, with
     bootstrap CIs and significance tests (chi-square, Kruskal-Wallis).
  3. Keyword and phrase frequency in comments by NPS category.

Saves charts to figures/ and a metrics summary to reports/metrics.json.

Run from the project root:  python src/analysis.py
(Run  python src/data_generator.py  first to create the CSV files.)
"""

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # non-interactive backend: no plot windows
import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns

from utils import (
    CATEGORY_ORDER,
    add_tenure_band,
    bootstrap_nps_ci,
    bootstrap_nps_difference,
    calculate_nps,
    compare_groups,
    keyword_frequency,
    monthly_nps,
    nps_by_group,
)

PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"
FIGURES_DIR = PROJECT_DIR / "figures"
REPORTS_DIR = PROJECT_DIR / "reports"

SEED = 42
N_BOOT = 2000
ALPHA = 0.05
DIMENSIONS = ["segment", "plan", "region", "acquisition_channel", "tenure_band"]
CATEGORY_COLORS = {"Detractor": "#d9534f", "Passive": "#f0ad4e", "Promoter": "#5cb85c"}


def section(title: str) -> None:
    """Print a section header."""
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")


def load_data() -> pd.DataFrame:
    """Load both CSV files and return responses joined with customer attributes."""
    customers_path = DATA_DIR / "customers.csv"
    responses_path = DATA_DIR / "survey_responses.csv"
    for path in (customers_path, responses_path):
        if not path.exists():
            raise SystemExit(f"Missing {path}. Run: python src/data_generator.py")
    customers = pd.read_csv(customers_path, parse_dates=["signup_date"])
    responses = pd.read_csv(responses_path, parse_dates=["survey_date"])
    merged = responses.merge(customers, on="customer_id", how="left", validate="1:1")
    return add_tenure_band(merged)


def plot_nps_by_group(results: dict[str, pd.DataFrame], overall: float) -> None:
    """One panel per dimension: NPS per group with 95% bootstrap CI error bars."""
    fig, axes = plt.subplots(2, 3, figsize=(15, 8))
    axes = axes.ravel()
    for ax, dim in zip(axes, DIMENSIONS):
        table = results[dim]
        err = [table["nps"] - table["ci_low"], table["ci_high"] - table["nps"]]
        ax.bar(table["group"], table["nps"], yerr=err, capsize=4, color="#6baed6")
        ax.axhline(overall, color="black", linestyle="--", linewidth=1, label="Overall NPS")
        ax.set_title(f"NPS by {dim}")
        ax.set_ylabel("NPS")
        ax.tick_params(axis="x", rotation=20)
        ax.legend(fontsize=8)
    for ax in axes[len(DIMENSIONS):]:
        ax.axis("off")
    fig.suptitle("NPS by group with 95% bootstrap CI (synthetic data)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "nps_by_group.png", dpi=120)
    plt.close(fig)


def plot_keywords(keywords: pd.DataFrame) -> None:
    """Horizontal bars of the most frequent terms for each NPS category."""
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    for ax, category in zip(axes, CATEGORY_ORDER):
        part = keywords[keywords["category"] == category].head(8).iloc[::-1]
        ax.barh(part["term"], part["share_pct"], color=CATEGORY_COLORS[category])
        ax.set_title(f"{category} comments")
        ax.set_xlabel("Share of comments containing the term (%)")
    fig.suptitle("Most frequent comment terms by NPS category (synthetic data)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "keywords_by_category.png", dpi=120)
    plt.close(fig)


def main() -> None:
    sns.set_theme(style="whitegrid")
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    df = load_data()
    print("NOTE: all data is SYNTHETIC, generated by src/data_generator.py")
    metrics: dict = {"data_note": "synthetic data", "n_responses": int(len(df))}

    # 1. Overall NPS and trend over time
    section("1. Overall NPS")
    overall = calculate_nps(df["nps_score"])
    low, high = bootstrap_nps_ci(df["nps_score"], n_boot=N_BOOT, seed=SEED)
    shares = df["nps_category"].value_counts(normalize=True).mul(100)
    print(f"Responses: {len(df)}")
    for cat in CATEGORY_ORDER:
        print(f"{cat} share (%): {shares.get(cat, 0.0):.1f}")
    print(f"NPS: {overall:.1f} (95% bootstrap CI {low:.1f} to {high:.1f})")
    metrics["overall"] = {
        "nps": overall,
        "ci_low": low,
        "ci_high": high,
        "category_share_pct": {c: float(shares.get(c, 0.0)) for c in CATEGORY_ORDER},
    }

    monthly = monthly_nps(df)
    print("\nNPS by survey month:")
    print(monthly.round(1).to_string(index=False))
    metrics["monthly_nps"] = monthly.to_dict("records")

    # 2. Segment comparison
    section("2. Segment comparison")
    results: dict[str, pd.DataFrame] = {}
    metrics["segments"] = {}
    for dim in DIMENSIONS:
        table = nps_by_group(df, dim, n_boot=N_BOOT, seed=SEED)
        tests = compare_groups(df, dim)
        # Bonferroni correction for the number of dimensions tested
        tests["chi2_p_bonferroni"] = min(1.0, tests["chi2_p_value"] * len(DIMENSIONS))
        tests["kruskal_p_bonferroni"] = min(1.0, tests["kruskal_p_value"] * len(DIMENSIONS))
        results[dim] = table

        best, worst = table.iloc[0], table.iloc[-1]
        diff, d_low, d_high = bootstrap_nps_difference(
            df.loc[df[dim] == best["group"], "nps_score"],
            df.loc[df[dim] == worst["group"], "nps_score"],
            n_boot=N_BOOT,
            seed=SEED,
        )
        extreme = {
            "best_group": best["group"],
            "worst_group": worst["group"],
            "nps_difference": diff,
            "ci_low": d_low,
            "ci_high": d_high,
        }

        print(f"\n--- {dim} ---")
        print(table.round(1).to_string(index=False))
        print(
            f"Chi-square (category x {dim}): chi2={tests['chi2']:.2f}, "
            f"dof={tests['chi2_dof']}, p={tests['chi2_p_value']:.4g}, "
            f"Bonferroni p={tests['chi2_p_bonferroni']:.4g}"
        )
        print(
            f"Kruskal-Wallis (score by {dim}): H={tests['kruskal_h']:.2f}, "
            f"p={tests['kruskal_p_value']:.4g}, "
            f"Bonferroni p={tests['kruskal_p_bonferroni']:.4g}"
        )
        print(
            f"Best vs worst: {best['group']} minus {worst['group']} = {diff:.1f} NPS points "
            f"(95% bootstrap CI {d_low:.1f} to {d_high:.1f}; groups picked after seeing data, "
            f"so this is optimistic)"
        )
        metrics["segments"][dim] = {
            "groups": table.to_dict("records"),
            "tests": tests,
            "best_vs_worst": extreme,
        }

    # 3. Text keywords
    section("3. Comment keywords by NPS category")
    keywords = keyword_frequency(df, top_n=10)
    n_comments = int(df["comment"].notna().sum())
    print(f"Responses with a comment: {n_comments} of {len(df)}")
    for cat in CATEGORY_ORDER:
        part = keywords[keywords["category"] == cat]
        print(f"\n{cat} (top terms, share of {cat.lower()} comments containing the term):")
        print(part[["term", "comments", "share_pct"]].round(1).to_string(index=False))
    metrics["comments_total"] = n_comments
    metrics["keywords"] = keywords.to_dict("records")

    # Charts and metrics file
    plot_nps_by_group(results, overall)
    plot_keywords(keywords)

    metrics_path = REPORTS_DIR / "metrics.json"
    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2, default=lambda o: o.item() if hasattr(o, "item") else str(o))

    section("Outputs")
    print(f"Saved charts to: {FIGURES_DIR} (nps_by_group.png, keywords_by_category.png)")
    print(f"Saved metrics to: {metrics_path}")


if __name__ == "__main__":
    main()
