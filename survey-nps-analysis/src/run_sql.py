"""Run the SQL queries from sql/queries.sql on the SYNTHETIC survey data.

Loads data/customers.csv and data/survey_responses.csv into an in-memory
SQLite database (pandas.to_sql), splits sql/queries.sql into statements,
runs each one and prints its description and the first rows of the result.

Run from the project root:  python src/run_sql.py
(Run  python src/data_generator.py  first to create the CSV files.)
"""

import re
import sqlite3
from pathlib import Path

import pandas as pd

PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"
SQL_FILE = PROJECT_DIR / "sql" / "queries.sql"

MAX_ROWS = 10  # rows printed per query


def load_database() -> sqlite3.Connection:
    """Create an in-memory SQLite database with both CSV tables."""
    paths = {
        "customers": DATA_DIR / "customers.csv",
        "survey_responses": DATA_DIR / "survey_responses.csv",
    }
    for path in paths.values():
        if not path.exists():
            raise SystemExit(f"Missing {path}. Run: python src/data_generator.py")

    conn = sqlite3.connect(":memory:")
    for name, path in paths.items():
        # Empty comments are read as NaN and stored as NULL
        pd.read_csv(path).to_sql(name, conn, index=False)
    return conn


def split_queries(sql_text: str) -> list[tuple[str, str]]:
    """Split the SQL file into (description, statement) pairs.

    Statements are separated by semicolons. The description is the comment
    line that starts with '-- Q<n>:'. Chunks without any SQL code are skipped.
    """
    queries = []
    for chunk in sql_text.split(";"):
        match = re.search(r"^--\s*(Q\d+:.*)$", chunk, flags=re.MULTILINE)
        code_lines = [
            line for line in chunk.splitlines()
            if line.strip() and not line.strip().startswith("--")
        ]
        if not code_lines:
            continue
        description = match.group(1).strip() if match else "(no description)"
        queries.append((description, chunk.strip()))
    return queries


def main() -> None:
    if not SQL_FILE.exists():
        raise SystemExit(f"Missing {SQL_FILE}")

    print("NOTE: all data is SYNTHETIC, generated by src/data_generator.py")
    conn = load_database()
    queries = split_queries(SQL_FILE.read_text(encoding="utf-8"))
    print(f"Loaded 2 tables into in-memory SQLite, running {len(queries)} queries")

    for description, statement in queries:
        print(f"\n{'=' * 70}\n{description}\n{'=' * 70}")
        result = pd.read_sql_query(statement, conn)
        print(result.head(MAX_ROWS).to_string(index=False))
        if len(result) > MAX_ROWS:
            print(f"... ({len(result)} rows in total, first {MAX_ROWS} shown)")

    conn.close()


if __name__ == "__main__":
    main()
