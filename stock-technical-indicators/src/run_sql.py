"""Run the SQL queries in sql/queries.sql against the synthetic stock data.

All data is SYNTHETIC (generated by src/data_generator.py).

The CSV files are loaded into an in-memory SQLite database with
pandas.to_sql. The query file is split into statements, each statement is
executed and its description and first rows are printed.

Reads:
    data/tickers.csv
    data/prices.csv
    sql/queries.sql

Run from the project root:
    python src/run_sql.py
"""

import sqlite3
from pathlib import Path

import pandas as pd

PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"
SQL_FILE = PROJECT_DIR / "sql" / "queries.sql"

MAX_ROWS = 10  # rows printed per query


def load_database():
    """Create an in-memory SQLite database from the CSV files."""
    conn = sqlite3.connect(":memory:")
    for name in ("tickers", "prices"):
        df = pd.read_csv(DATA_DIR / f"{name}.csv")
        df.to_sql(name, conn, index=False, if_exists="replace")
    return conn


def split_queries(text):
    """Split the SQL file into (description, statement) pairs.

    Statements end with a semicolon. The description is taken from the
    comment line starting with '-- Q'. Chunks that only contain comments
    are skipped.
    """
    queries = []
    for chunk in text.split(";"):
        lines = chunk.strip().splitlines()
        has_sql = any(line.strip() and not line.strip().startswith("--") for line in lines)
        if not has_sql:
            continue
        description = next(
            (line.strip()[2:].strip() for line in lines if line.strip().startswith("-- Q")),
            "(no description)",
        )
        queries.append((description, chunk.strip()))
    return queries


def main():
    conn = load_database()
    queries = split_queries(SQL_FILE.read_text(encoding="utf-8"))
    print(f"Loaded tables into in-memory SQLite, running {len(queries)} queries")

    for description, statement in queries:
        print("\n" + "=" * 80)
        print(description)
        print("=" * 80)
        result = pd.read_sql_query(statement, conn)
        print(f"({len(result)} rows, showing the first {min(len(result), MAX_ROWS)})")
        print(result.head(MAX_ROWS).to_string(index=False))

    conn.close()


if __name__ == "__main__":
    main()
