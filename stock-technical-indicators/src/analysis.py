"""Backtest technical-indicator strategies against buy-and-hold.

All data is SYNTHETIC (generated by src/data_generator.py).

Strategies (long/flat, daily close):
    - sma_crossover:   long while SMA(20) > SMA(50)
    - rsi_reversion:   long after RSI(14) < 30, flat once RSI(14) > 50
    - macd_crossover:  long while MACD(12, 26) > signal line (9)
    - buy_and_hold:    benchmark

Parameters are fixed in advance (common textbook defaults) and are not tuned,
so no train/test split is needed for this rule-based comparison.

Reads:
    data/prices.csv

Writes (relative to the project root):
    figures/equity_curves.png
    figures/sharpe_by_strategy.png
    reports/metrics.json

Run from the project root:
    python src/analysis.py
"""

import json
import os
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # non-interactive backend
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

sys.path.insert(0, str(Path(__file__).resolve().parent))
import utils  # noqa: E402

PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"
FIGURES_DIR = PROJECT_DIR / "figures"
REPORTS_DIR = PROJECT_DIR / "reports"

COST_RATE = 0.001  # 0.1% per position change
PARAMS = {
    "sma_crossover": {"short": 20, "long": 50},
    "rsi_reversion": {"window": 14, "entry": 30.0, "exit_level": 50.0},
    "macd_crossover": {"fast": 12, "slow": 26, "signal": 9},
    "cost_rate": COST_RATE,
}

STRATEGIES = {
    "buy_and_hold": lambda c: utils.buy_and_hold_position(c),
    "sma_crossover": lambda c: utils.sma_crossover_position(c, **PARAMS["sma_crossover"]),
    "rsi_reversion": lambda c: utils.rsi_reversion_position(c, **PARAMS["rsi_reversion"]),
    "macd_crossover": lambda c: utils.macd_crossover_position(c, **PARAMS["macd_crossover"]),
}


def load_prices():
    """Load prices sorted by ticker and date."""
    prices = pd.read_csv(DATA_DIR / "prices.csv", parse_dates=["date"])
    return prices.sort_values(["ticker", "date"]).reset_index(drop=True)


def run_backtests(prices):
    """Run every strategy on every ticker.

    Returns (metrics DataFrame, dict of equity curves keyed by (ticker, strategy)).
    """
    rows = []
    curves = {}
    for ticker, grp in prices.groupby("ticker"):
        grp = grp.set_index("date")
        close = grp["close"]
        log_ret = np.log(close / close.shift(1))
        for name, make_position in STRATEGIES.items():
            position = make_position(close)
            # Buy-and-hold pays no ongoing costs beyond the single entry
            bt = utils.backtest(log_ret, position, cost_rate=COST_RATE)
            curves[(ticker, name)] = bt["equity"]
            rows.append({"ticker": ticker, "strategy": name, **utils.performance_metrics(bt)})
    return pd.DataFrame(rows), curves


def summarise(metrics):
    """Compare each active strategy with buy-and-hold on the same ticker."""
    bh = metrics[metrics["strategy"] == "buy_and_hold"].set_index("ticker")
    summary = {}
    for name in STRATEGIES:
        if name == "buy_and_hold":
            continue
        sub = metrics[metrics["strategy"] == name].set_index("ticker")
        summary[name] = {
            "n_tickers": int(len(sub)),
            "tickers_with_higher_sharpe_than_buy_and_hold": int((sub["sharpe_ratio"] > bh["sharpe_ratio"]).sum()),
            "tickers_with_higher_total_return_than_buy_and_hold": int((sub["total_return"] > bh["total_return"]).sum()),
            "tickers_with_smaller_drawdown_than_buy_and_hold": int((sub["max_drawdown"] > bh["max_drawdown"]).sum()),
            "mean_sharpe_ratio": float(sub["sharpe_ratio"].mean()),
            "mean_max_drawdown": float(sub["max_drawdown"].mean()),
            "mean_n_trades": float(sub["n_trades"].mean()),
        }
    summary["buy_and_hold"] = {
        "mean_sharpe_ratio": float(bh["sharpe_ratio"].mean()),
        "mean_max_drawdown": float(bh["max_drawdown"].mean()),
    }
    return summary


def plot_equity_curves(curves, tickers):
    """Equity curves of all strategies, one panel per ticker."""
    fig, axes = plt.subplots(2, 2, figsize=(13, 8), sharex=True)
    for ax, ticker in zip(axes.ravel(), tickers):
        for name in STRATEGIES:
            ax.plot(curves[(ticker, name)], label=name)
        ax.set_title(ticker)
        ax.set_ylabel("Equity (start = 1.0)")
    for ax in axes[-1]:
        ax.set_xlabel("Date")
    axes[0, 0].legend(title="Strategy", fontsize=8)
    fig.suptitle("Equity curves on synthetic prices (after transaction costs)")
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "equity_curves.png", dpi=120)
    plt.close(fig)


def plot_sharpe(metrics):
    """Grouped bar chart of Sharpe ratios by ticker and strategy."""
    fig, ax = plt.subplots(figsize=(10, 5))
    sns.barplot(data=metrics, x="ticker", y="sharpe_ratio", hue="strategy", ax=ax)
    ax.axhline(0, color="black", linewidth=0.8)
    ax.set_title("Annualised Sharpe ratio by ticker and strategy")
    ax.set_xlabel("Ticker")
    ax.set_ylabel("Sharpe ratio (risk-free rate = 0)")
    ax.legend(title="Strategy", fontsize=8)
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / "sharpe_by_strategy.png", dpi=120)
    plt.close(fig)


def main():
    os.makedirs(FIGURES_DIR, exist_ok=True)
    os.makedirs(REPORTS_DIR, exist_ok=True)
    sns.set_theme(style="whitegrid")

    prices = load_prices()
    metrics, curves = run_backtests(prices)
    tickers = sorted(prices["ticker"].unique())

    print("=== Backtest metrics per ticker and strategy ===")
    print(f"(transaction cost per position change: {COST_RATE:.2%}, risk-free rate: 0)")
    show = metrics.set_index(["ticker", "strategy"]).round(4)
    print(show.to_string())

    summary = summarise(metrics)
    print("\n=== Summary versus buy-and-hold ===")
    for name, values in summary.items():
        print(f"\n{name}")
        for key, value in values.items():
            print(f"  {key}: {round(value, 4) if isinstance(value, float) else value}")

    plot_equity_curves(curves, tickers)
    plot_sharpe(metrics)
    print(f"\nSaved 2 charts to {FIGURES_DIR}")

    report = {
        "data_note": "Synthetic data generated by src/data_generator.py (seed 42)",
        "parameters": PARAMS,
        "metrics": json.loads(metrics.round(6).to_json(orient="records")),
        "summary_vs_buy_and_hold": summary,
    }
    with open(REPORTS_DIR / "metrics.json", "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2)
    print(f"Saved metrics to {REPORTS_DIR / 'metrics.json'}")


if __name__ == "__main__":
    main()
