"""Exploratory data analysis for the synthetic stock price data.

All data is SYNTHETIC (generated by src/data_generator.py).

Reads:
    data/tickers.csv
    data/prices.csv

Writes (relative to the project root):
    figures/close_prices.png
    figures/return_distribution.png
    figures/volume_vs_abs_return.png

Run from the project root:
    python src/eda.py
"""

import os
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # non-interactive backend, no display needed
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from matplotlib.ticker import FuncFormatter, PercentFormatter

PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"
FIGURES_DIR = PROJECT_DIR / "figures"

TRADING_DAYS = 252


def load_data():
    """Load the CSV files and parse dates."""
    tickers = pd.read_csv(DATA_DIR / "tickers.csv")
    prices = pd.read_csv(DATA_DIR / "prices.csv", parse_dates=["date"])
    return tickers, prices


def add_returns(prices):
    """Add daily log returns per ticker (first day of each ticker is NaN)."""
    prices = prices.sort_values(["ticker", "date"]).reset_index(drop=True)
    prices["log_return"] = prices.groupby("ticker")["close"].transform(
        lambda s: np.log(s / s.shift(1))
    )
    prices["abs_return"] = prices["log_return"].abs()
    return prices


def print_overview(name, df):
    """Print shape, dtypes and missing values for a table."""
    print(f"\n=== {name}: overview ===")
    print(f"Shape: {df.shape}")
    print("\nDtypes:")
    print(df.dtypes.to_string())
    print("\nMissing values per column:")
    print(df.isna().sum().to_string())


def print_quality_checks(prices):
    """Basic data quality checks on the price table."""
    print("\n=== Data quality checks ===")
    print(f"Duplicate (date, ticker) rows: {prices.duplicated(['date', 'ticker']).sum()}")
    bad_high = (prices["high"] < prices[["open", "close", "low"]].max(axis=1)).sum()
    bad_low = (prices["low"] > prices[["open", "close", "high"]].min(axis=1)).sum()
    print(f"Rows where high is below open/close/low: {bad_high}")
    print(f"Rows where low is above open/close/high: {bad_low}")
    print(f"Rows with non-positive prices: {(prices[['open', 'high', 'low', 'close']] <= 0).any(axis=1).sum()}")
    print(f"Rows with volume < 1: {(prices['volume'] < 1).sum()}")


def print_descriptive_stats(prices):
    """Descriptive statistics for the main numeric columns."""
    print("\n=== Descriptive statistics ===")
    cols = ["open", "high", "low", "close", "volume", "log_return"]
    print(prices[cols].describe().round(4).T.to_string())


def print_aggregations(tickers, prices):
    """Print meaningful aggregations."""
    # 1. Per-ticker summary: price range, realised return and volatility
    per_ticker = prices.groupby("ticker").agg(
        first_close=("close", "first"),
        last_close=("close", "last"),
        min_close=("close", "min"),
        max_close=("close", "max"),
        mean_daily_return=("log_return", "mean"),
        daily_volatility=("log_return", "std"),
        avg_volume=("volume", "mean"),
    )
    per_ticker["total_return"] = per_ticker["last_close"] / per_ticker["first_close"] - 1
    per_ticker["annualised_volatility"] = per_ticker["daily_volatility"] * np.sqrt(TRADING_DAYS)
    per_ticker = per_ticker.join(
        tickers.set_index("ticker")[["sector", "annual_volatility"]]
    ).rename(columns={"annual_volatility": "assumed_calm_vol"})
    print("\n=== 1. Per-ticker summary ===")
    print(per_ticker.round(4).T.to_string())

    # 2. Volatility regimes: share of days and realised volatility
    regime = (
        prices.groupby(["ticker", "volatility_regime"])
        .agg(days=("close", "size"), daily_vol=("log_return", "std"), avg_volume=("volume", "mean"))
        .round(4)
    )
    print("\n=== 2. Volatility regimes per ticker ===")
    print(regime.to_string())

    # 3. Average monthly return per ticker (calendar month, sum of log returns)
    prices = prices.assign(month=prices["date"].dt.to_period("M"))
    monthly = prices.groupby(["ticker", "month"])["log_return"].sum().reset_index()
    monthly_summary = monthly.groupby("ticker")["log_return"].agg(
        mean="mean", std="std", best="max", worst="min"
    )
    print("\n=== 3. Monthly log return summary per ticker ===")
    print(monthly_summary.round(4).to_string())

    # 4. Tail behaviour: skewness and excess kurtosis of daily returns
    tails = prices.groupby("ticker")["log_return"].agg(
        skew="skew", excess_kurtosis=lambda s: s.kurt()
    )
    print("\n=== 4. Return skewness and excess kurtosis ===")
    print(tails.round(4).to_string())

    # 5. Correlation between tickers' daily returns
    wide = prices.pivot(index="date", columns="ticker", values="log_return")
    print("\n=== 5. Correlation of daily log returns between tickers ===")
    print(wide.corr().round(4).to_string())

    # Volume vs absolute return
    corr = prices[["volume", "abs_return"]].corr().iloc[0, 1]
    print(f"\nCorrelation between volume and absolute return (all tickers): {corr:.4f}")


def save_figure(fig, filename):
    """Apply a tight layout, save the figure into FIGURES_DIR and close it."""
    fig.tight_layout()
    fig.savefig(FIGURES_DIR / filename, dpi=120)
    plt.close(fig)


def plot_close_prices(prices):
    """Line chart of close prices rebased to 100 for comparability."""
    fig, ax = plt.subplots(figsize=(10, 5))
    for ticker, grp in prices.groupby("ticker"):
        ax.plot(grp["date"], grp["close"] / grp["close"].iloc[0] * 100, label=ticker)
    ax.set_title("Synthetic close prices rebased to 100")
    ax.set_xlabel("Date")
    ax.set_ylabel("Rebased close price (first close = 100)")
    ax.legend(title="Ticker")
    save_figure(fig, "close_prices.png")


def plot_return_distribution(prices):
    """Histogram of daily log returns per ticker and by volatility regime."""
    data = prices.dropna(subset=["log_return"])
    fig, axes = plt.subplots(1, 2, figsize=(12, 5))

    sns.histplot(
        data=data, x="log_return", hue="ticker", bins=60,
        element="step", stat="density", common_norm=False, ax=axes[0],
    )
    axes[0].set_title("Daily log returns by ticker")
    axes[0].set_xlabel("Daily log return")
    axes[0].set_ylabel("Density")

    sns.boxplot(data=data, x="ticker", y="log_return", hue="volatility_regime", ax=axes[1])
    axes[1].set_title("Daily log returns by volatility regime")
    axes[1].set_xlabel("Ticker")
    axes[1].set_ylabel("Daily log return")
    axes[1].legend(title="Regime")

    save_figure(fig, "return_distribution.png")


def plot_volume_vs_return(prices):
    """Scatter of volume against absolute daily return, with readable axis units."""
    data = prices.dropna(subset=["abs_return"])
    fig, ax = plt.subplots(figsize=(9, 5.5))
    sns.scatterplot(
        data=data, x="abs_return", y="volume", hue="ticker",
        alpha=0.4, s=15, ax=ax,
    )
    ax.set_title("Volume vs absolute daily log return (synthetic data)")
    ax.set_xlabel("Absolute daily log return (ticks in %)")
    ax.set_ylabel("Volume (millions of shares)")
    # Show returns as percentages and volume in millions instead of raw decimals
    ax.xaxis.set_major_formatter(PercentFormatter(xmax=1.0, decimals=0))
    ax.yaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v / 1e6:.1f}"))
    ax.legend(title="Ticker", loc="upper right")
    save_figure(fig, "volume_vs_abs_return.png")


def main():
    os.makedirs(FIGURES_DIR, exist_ok=True)
    sns.set_theme(style="whitegrid")

    tickers, prices = load_data()
    print_overview("tickers", tickers)
    print_overview("prices", prices)

    prices = add_returns(prices)
    print_quality_checks(prices)
    print_descriptive_stats(prices)
    print_aggregations(tickers, prices)

    plot_close_prices(prices)
    plot_return_distribution(prices)
    plot_volume_vs_return(prices)
    print(f"\nSaved 3 charts to {FIGURES_DIR}")


if __name__ == "__main__":
    main()
