"""Reusable helpers for the employee attrition analysis.

Contains data loading, feature preparation, the logistic regression pipeline
and metric functions. They live here (not in analysis.py) so they can be
unit-tested with pytest.

All data is SYNTHETIC, generated by src/data_generator.py.
"""

from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_recall_curve,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

# Paths are relative to the project root, not to the current working directory
PROJECT_DIR = Path(__file__).resolve().parents[1]
DATA_DIR = PROJECT_DIR / "data"

TARGET = "attrition"

NUMERIC_FEATURES = [
    "age",
    "job_level",
    "years_at_company",
    "monthly_income",
    "distance_from_home_km",
    "num_projects",
    "years_since_last_promotion",
    "job_satisfaction",
    "work_life_balance",
    "manager_support",
]
CATEGORICAL_FEATURES = ["department", "gender", "overtime"]
FEATURES = NUMERIC_FEATURES + CATEGORICAL_FEATURES


def load_data(data_dir: Path = DATA_DIR) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Load the employees and survey tables."""
    employees = pd.read_csv(Path(data_dir) / "employees.csv")
    surveys = pd.read_csv(Path(data_dir) / "satisfaction_surveys.csv")
    return employees, surveys


def merge_data(employees: pd.DataFrame, surveys: pd.DataFrame) -> pd.DataFrame:
    """Left-join surveys onto employees.

    Employees who did not answer the survey keep NaN in the survey columns.
    The join is validated as one-to-one: if employee_id is duplicated in either
    table, pandas raises MergeError instead of silently multiplying rows, which
    would double-count employees and leak them into both train and test sets.
    """
    return employees.merge(surveys, on="employee_id", how="left", validate="one_to_one")


def split_features_target(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.Series]:
    """Return the feature matrix X and the binary target y."""
    return df[FEATURES].copy(), df[TARGET].astype(int)


def build_preprocessor() -> ColumnTransformer:
    """Preprocessing: impute + scale numeric columns, one-hot encode categoricals.

    - Numeric: median imputation (survey non-respondents), then standardisation,
      so coefficients are per 1 standard deviation and comparable.
    - Categorical: one-hot with the first category dropped (avoids collinearity).
    The imputer and scaler are fitted inside the pipeline, i.e. on training
    data only, which prevents leakage into the test set.
    """
    numeric = Pipeline(
        [("impute", SimpleImputer(strategy="median")), ("scale", StandardScaler())]
    )
    categorical = OneHotEncoder(drop="first", sparse_output=False)
    return ColumnTransformer(
        [
            ("num", numeric, NUMERIC_FEATURES),
            ("cat", categorical, CATEGORICAL_FEATURES),
        ],
        verbose_feature_names_out=False,
    )


def build_model() -> Pipeline:
    """Preprocessing + unpenalised logistic regression.

    No penalty is used so the coefficients are directly comparable with the
    statsmodels fit and easy to interpret as log-odds.
    """
    return Pipeline(
        [
            ("prep", build_preprocessor()),
            ("clf", LogisticRegression(penalty=None, max_iter=2000)),
        ]
    )


def best_f1_threshold(y_true, y_prob) -> float:
    """Probability threshold that maximises F1 on the given data."""
    precision, recall, thresholds = precision_recall_curve(y_true, y_prob)
    f1 = 2 * precision * recall / np.maximum(precision + recall, 1e-12)
    # precision/recall have one more element than thresholds
    return float(thresholds[int(np.argmax(f1[:-1]))])


def compute_metrics(y_true, y_prob, threshold: float = 0.5) -> dict:
    """Classification metrics for predicted probabilities at a threshold."""
    y_true = np.asarray(y_true)
    y_prob = np.asarray(y_prob)
    y_pred = (y_prob >= threshold).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    return {
        "threshold": float(threshold),
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "precision": float(precision_score(y_true, y_pred, zero_division=0)),
        "recall": float(recall_score(y_true, y_pred, zero_division=0)),
        "f1": float(f1_score(y_true, y_pred, zero_division=0)),
        "roc_auc": float(roc_auc_score(y_true, y_prob)),
        "average_precision": float(average_precision_score(y_true, y_prob)),
        "true_negatives": int(tn),
        "false_positives": int(fp),
        "false_negatives": int(fn),
        "true_positives": int(tp),
    }


def odds_ratio_table(model: Pipeline, X_train: pd.DataFrame, y_train: pd.Series) -> pd.DataFrame:
    """Odds ratios with 95% CI and p-values from a statsmodels Logit.

    The design matrix is produced by the fitted preprocessing step, so the
    numeric odds ratios are per +1 standard deviation and the categorical ones
    compare against the dropped reference category.
    """
    prep = model.named_steps["prep"]
    names = list(prep.get_feature_names_out())
    design = pd.DataFrame(prep.transform(X_train), columns=names, index=X_train.index)
    result = sm.Logit(y_train.to_numpy(), sm.add_constant(design)).fit(disp=0)

    ci = result.conf_int()
    table = pd.DataFrame(
        {
            "feature": result.params.index,
            "coef": result.params.to_numpy(),
            "odds_ratio": np.exp(result.params.to_numpy()),
            "ci_low": np.exp(ci[0].to_numpy()),
            "ci_high": np.exp(ci[1].to_numpy()),
            "p_value": result.pvalues.to_numpy(),
        }
    )
    return table[table["feature"] != "const"].reset_index(drop=True)
