"""Main analysis: group tests and delay classifier on SYNTHETIC data.

Steps:
    1. Chi-square tests of delay vs. carrier, airport, hour and weekend.
    2. Stratified train/test split (80/20, random_state=42).
    3. Train a baseline logistic regression and a random forest.
    4. Evaluate on the held-out test set, compute permutation importance.
    5. Save charts to figures/ and metrics to reports/metrics.json.

Run from the project root (after python src/data_generator.py):
    python src/analysis.py
"""
import json
import os
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # non-interactive backend
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.inspection import permutation_importance
from sklearn.metrics import RocCurveDisplay
from sklearn.model_selection import train_test_split

sys.path.insert(0, str(Path(__file__).resolve().parent))
import utils  # noqa: E402

FIG_DIR = utils.PROJECT_DIR / "figures"
REPORT_DIR = utils.PROJECT_DIR / "reports"
TEST_SIZE = 0.2


def run_group_tests(df):
    """Chi-square tests of the delay flag against key categorical drivers."""
    results = [utils.chi_square_delay_test(df, c)
               for c in ["carrier_code", "origin", "scheduled_dep_hour",
                         "is_weekend"]]
    print("\n=== Chi-square tests: delay flag vs. group ===")
    for r in results:
        print(f"{r['column']:<20} chi2={r['chi2']:.2f}  dof={r['dof']}  "
              f"p-value={r['p_value']:.4g}  Cramer's V={r['cramers_v']:.3f}")
    return results


def plot_roc(models, X_test, y_test):
    """Save ROC curves of all models on the test set."""
    fig, ax = plt.subplots(figsize=(6, 5))
    for name, model in models.items():
        RocCurveDisplay.from_predictions(
            y_test, model.predict_proba(X_test)[:, 1], name=name, ax=ax)
    ax.plot([0, 1], [0, 1], "k--", label="Random guess")
    ax.set_title("ROC curves on the test set (synthetic data)")
    ax.legend(loc="lower right")
    fig.tight_layout()
    fig.savefig(FIG_DIR / "roc_curves.png", dpi=120)
    plt.close(fig)


def plot_importance(importance):
    """Save a bar chart of permutation importance (drop in ROC AUC)."""
    fig, ax = plt.subplots(figsize=(7, 4.5))
    sns.barplot(x=importance.values, y=importance.index, ax=ax,
                color="steelblue")
    ax.set_title("Permutation importance, random forest (synthetic data)")
    ax.set_xlabel("Mean drop in test ROC AUC")
    ax.set_ylabel("Feature")
    fig.tight_layout()
    fig.savefig(FIG_DIR / "feature_importance.png", dpi=120)
    plt.close(fig)


def main():
    """Run the analysis end to end."""
    airports, _, flights = utils.load_tables()
    df = utils.build_model_frame(flights, airports)
    X, y = utils.get_X_y(df)
    print(f"Rows: {len(df)}  |  overall delay rate: {y.mean():.3f}")

    group_tests = run_group_tests(df)

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=TEST_SIZE, stratify=y, random_state=utils.RANDOM_STATE)
    print(f"\nTrain rows: {len(X_train)}  |  test rows: {len(X_test)}")
    print(f"Delay rate train: {y_train.mean():.3f}  test: {y_test.mean():.3f}")

    baseline_acc = utils.majority_baseline_accuracy(y_train, y_test)
    print(f"Majority-class baseline accuracy (test): {baseline_acc:.3f}")

    models = utils.build_models()
    all_metrics = {}
    for name, model in models.items():
        model.fit(X_train, y_train)
        pred = model.predict(X_test)
        proba = model.predict_proba(X_test)[:, 1]
        all_metrics[name] = utils.compute_metrics(y_test, pred, proba)
        print(f"\n=== Test metrics: {name} ===")
        for metric, value in all_metrics[name].items():
            print(f"{metric:<10} {value:.3f}")

    # Permutation importance on the raw input columns (random forest)
    forest = models["random_forest"]
    perm = permutation_importance(
        forest, X_test, y_test, scoring="roc_auc", n_repeats=5,
        random_state=utils.RANDOM_STATE, n_jobs=1)
    importance = (
        __import__("pandas").Series(perm.importances_mean, index=X_test.columns)
        .sort_values(ascending=False))
    print("\n=== Permutation importance (drop in test ROC AUC) ===")
    print(importance.round(4).to_string())

    os.makedirs(FIG_DIR, exist_ok=True)
    plot_roc(models, X_test, y_test)
    plot_importance(importance)

    summary = {
        "note": "Synthetic data generated by this project; not real flights.",
        "n_rows": int(len(df)),
        "overall_delay_rate": float(y.mean()),
        "test_size": TEST_SIZE,
        "random_state": utils.RANDOM_STATE,
        "features": utils.FEATURES,
        "majority_baseline_accuracy": baseline_acc,
        "chi_square_tests": group_tests,
        "model_metrics": all_metrics,
        "permutation_importance_roc_auc": {
            k: float(v) for k, v in importance.items()},
    }
    os.makedirs(REPORT_DIR, exist_ok=True)
    with open(REPORT_DIR / "metrics.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print(f"\nCharts saved to: {FIG_DIR}")
    print(f"Metrics saved to: {REPORT_DIR / 'metrics.json'}")


if __name__ == "__main__":
    main()
